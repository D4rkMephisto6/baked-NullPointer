CREATE OR REPLACE VIEW pos_schema.v_low_stock_ingredients AS
SELECT i.ingredient_id, i.sku, i.name AS ingredient_name,
       u.code AS unit_code,
       COALESCE(s.quantity_on_hand, 0)::NUMERIC(14,3) AS quantity_on_hand,
       i.min_stock,
       CASE WHEN COALESCE(s.quantity_on_hand, 0) <= 0 THEN 'AGOTADO' ELSE 'STOCK_BAJO' END AS alert_status
