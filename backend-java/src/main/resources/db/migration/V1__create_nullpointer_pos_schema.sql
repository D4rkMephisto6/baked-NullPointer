-- Sprint 3: ingredientes, recetas, proveedores, compras, stock y mermas
-- ============================================================================

CREATE TABLE IF NOT EXISTS pos_schema.units_of_measure (
    unit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(12) NOT NULL UNIQUE,
    name          VARCHAR(50) NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS pos_schema.ingredients (
    ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_unit_id  BIGINT NOT NULL REFERENCES pos_schema.units_of_measure(unit_id),
    sku           VARCHAR(40) UNIQUE,
    name          VARCHAR(120) NOT NULL UNIQUE,
    description   TEXT,
    min_stock     NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Un producto tiene muchos ingredientes en su receta y un ingrediente puede
-- utilizarse en muchos productos: esta tabla resuelve la relación N:M.
-- quantity_required siempre se expresa en la unidad base del ingrediente.
CREATE TABLE IF NOT EXISTS pos_schema.recipe_ingredients (
    recipe_ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT NOT NULL REFERENCES pos_schema.products(product_id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES pos_schema.ingredients(ingredient_id) ON DELETE RESTRICT,
    quantity_required NUMERIC(14,4) NOT NULL CHECK (quantity_required > 0),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (product_id, ingredient_id)
);
CREATE INDEX IF NOT EXISTS ix_recipe_ingredients_ingredient ON pos_schema.recipe_ingredients(ingredient_id);

CREATE TABLE IF NOT EXISTS pos_schema.inventory_stock (
    ingredient_id BIGINT PRIMARY KEY REFERENCES pos_schema.ingredients(ingredient_id) ON DELETE RESTRICT,
    quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Registro inmutable de entradas/salidas. El trigger posterior actualiza
-- inventory_stock al insertar cada movimiento.
CREATE TABLE IF NOT EXISTS pos_schema.inventory_movements (
    inventory_movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES pos_schema.ingredients(ingredient_id) ON DELETE RESTRICT,
    movement_type VARCHAR(24) NOT NULL
                  CHECK (movement_type IN ('COMPRA','VENTA','MERMA','AJUSTE_ENTRADA','AJUSTE_SALIDA','REVERSA')),
    quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
    unit_cost     NUMERIC(14,4) CHECK (unit_cost IS NULL OR unit_cost >= 0),
    reference_type VARCHAR(30),
    reference_id  BIGINT,
    notes         VARCHAR(500),
    created_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_movement_sign CHECK (
       (movement_type IN ('COMPRA','AJUSTE_ENTRADA','REVERSA') AND quantity_delta > 0)
       OR (movement_type IN ('VENTA','MERMA','AJUSTE_SALIDA') AND quantity_delta < 0)
    )
);
CREATE INDEX IF NOT EXISTS ix_inventory_movements_ingredient_date
    ON pos_schema.inventory_movements(ingredient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_inventory_movements_reference
    ON pos_schema.inventory_movements(reference_type, reference_id);
-- Evita duplicar una salida de venta/entrada de compra/merma por referencia.
CREATE UNIQUE INDEX IF NOT EXISTS ux_inventory_movement_reference
    ON pos_schema.inventory_movements(ingredient_id, movement_type, reference_type, reference_id)
    WHERE reference_id IS NOT NULL AND reference_type IS NOT NULL;

CREATE TABLE IF NOT EXISTS pos_schema.suppliers (
    supplier_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR(160) NOT NULL,
    tax_id        VARCHAR(20),
    contact_name  VARCHAR(120),
    phone         VARCHAR(25),
    email         VARCHAR(160),
    address       VARCHAR(250),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_suppliers_tax_id ON pos_schema.suppliers(tax_id) WHERE tax_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS pos_schema.purchases (
    purchase_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   BIGINT NOT NULL REFERENCES pos_schema.suppliers(supplier_id) ON DELETE RESTRICT,
    purchase_code VARCHAR(40) UNIQUE,
    supplier_invoice_number VARCHAR(60),
    status        VARCHAR(20) NOT NULL DEFAULT 'BORRADOR'
                  CHECK (status IN ('BORRADOR','RECIBIDA','ANULADA')),
    purchased_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    received_at   TIMESTAMPTZ,
    created_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    received_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    notes         TEXT,
    total_amount  NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_purchases_supplier_date ON pos_schema.purchases(supplier_id, purchased_at DESC);

CREATE TABLE IF NOT EXISTS pos_schema.purchase_items (
    purchase_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id   BIGINT NOT NULL REFERENCES pos_schema.purchases(purchase_id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES pos_schema.ingredients(ingredient_id) ON DELETE RESTRICT,
    quantity      NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    unit_cost     NUMERIC(14,4) NOT NULL CHECK (unit_cost >= 0),
    line_total    NUMERIC(14,2) GENERATED ALWAYS AS (ROUND(quantity * unit_cost, 2)) STORED
);
CREATE INDEX IF NOT EXISTS ix_purchase_items_purchase ON pos_schema.purchase_items(purchase_id);

CREATE TABLE IF NOT EXISTS pos_schema.waste_records (
    waste_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waste_code    VARCHAR(40) UNIQUE,
    status        VARCHAR(20) NOT NULL DEFAULT 'BORRADOR'
                  CHECK (status IN ('BORRADOR','CONFIRMADA','ANULADA')),
    reason        VARCHAR(250) NOT NULL,
    notes         TEXT,
    recorded_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    confirmed_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    recorded_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    confirmed_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS pos_schema.waste_items (
    waste_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waste_record_id BIGINT NOT NULL REFERENCES pos_schema.waste_records(waste_record_id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES pos_schema.ingredients(ingredient_id) ON DELETE RESTRICT,
    quantity      NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    estimated_unit_cost NUMERIC(14,4) CHECK (estimated_unit_cost IS NULL OR estimated_unit_cost >= 0),
    notes         VARCHAR(250)
);
CREATE INDEX IF NOT EXISTS ix_waste_items_record ON pos_schema.waste_items(waste_record_id);

