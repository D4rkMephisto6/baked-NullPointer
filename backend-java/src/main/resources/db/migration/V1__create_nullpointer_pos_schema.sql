CREATE TABLE IF NOT EXISTS pos_schema.cash_registers (
    cash_register_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    register_code VARCHAR(30) NOT NULL UNIQUE,
    name          VARCHAR(80) NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS pos_schema.cash_sessions (
    cash_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_register_id BIGINT NOT NULL REFERENCES pos_schema.cash_registers(cash_register_id) ON DELETE RESTRICT,
    opened_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    closed_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    status        VARCHAR(15) NOT NULL DEFAULT 'ABIERTA' CHECK (status IN ('ABIERTA','CERRADA')),
    opening_amount NUMERIC(12,2) NOT NULL CHECK (opening_amount >= 0),
    opened_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_at     TIMESTAMPTZ,
    closing_notes TEXT,
    CONSTRAINT cash_session_closure_consistency CHECK (
       (status = 'ABIERTA' AND closed_at IS NULL)
       OR (status = 'CERRADA' AND closed_at IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_one_open_session_per_register
    ON pos_schema.cash_sessions(cash_register_id) WHERE status = 'ABIERTA';
CREATE INDEX IF NOT EXISTS ix_cash_sessions_opened_by ON pos_schema.cash_sessions(opened_by_user_id, opened_at DESC);

-- Cada fila representa un medio de pago; dos o más filas permiten pago mixto.
CREATE TABLE IF NOT EXISTS pos_schema.payments (
    payment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES pos_schema.orders(order_id) ON DELETE RESTRICT,
    cash_session_id BIGINT REFERENCES pos_schema.cash_sessions(cash_session_id) ON DELETE RESTRICT,
    registered_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('EFECTIVO','YAPE','PLIN','TARJETA','TRANSFERENCIA','OTRO')),
    status        VARCHAR(18) NOT NULL DEFAULT 'REGISTRADO'
                  CHECK (status IN ('REGISTRADO','VERIFICADO','RECHAZADO','ANULADO')),
    amount        NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    cash_received NUMERIC(12,2),
    change_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (change_amount >= 0),
    operation_code VARCHAR(100),
    verification_note VARCHAR(250),
    paid_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    verified_at   TIMESTAMPTZ,
