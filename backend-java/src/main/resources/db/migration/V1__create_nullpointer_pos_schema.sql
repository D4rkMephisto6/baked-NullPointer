CREATE TRIGGER trg_confirm_waste_stock
BEFORE UPDATE OF status ON pos_schema.waste_records
FOR EACH ROW EXECUTE FUNCTION pos_schema.fn_confirm_waste_stock();

-- Al marcar una comanda como PAGADO, descuenta ingredientes según sus recetas.
-- Si no hay stock suficiente, PostgreSQL cancela toda la actualización y Spring
-- puede devolver al cajero un error de negocio. Productos sin receta no descuentan stock.
CREATE OR REPLACE FUNCTION pos_schema.fn_deduct_stock_for_paid_order()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
BEGIN
    IF NEW.status = 'PAGADO' AND OLD.status IS DISTINCT FROM 'PAGADO' THEN
        FOR r IN
            SELECT ri.ingredient_id,
                   SUM(oi.quantity * ri.quantity_required)::NUMERIC(14,3) AS total_required
            FROM pos_schema.order_items oi
            JOIN pos_schema.recipe_ingredients ri ON ri.product_id = oi.product_id
            WHERE oi.order_id = NEW.order_id
              AND oi.status <> 'ANULADO'
            GROUP BY ri.ingredient_id
        LOOP
            INSERT INTO pos_schema.inventory_movements
              (ingredient_id, movement_type, quantity_delta, reference_type, reference_id,
               notes, created_by_user_id)
            VALUES
              (r.ingredient_id, 'VENTA', -r.total_required, 'ORDER', NEW.order_id,
               'Descuento automático por venta de comanda ' || NEW.order_id,
               COALESCE(NEW.paid_by_user_id, NEW.waiter_user_id));
        END LOOP;
        NEW.paid_at := COALESCE(NEW.paid_at, NOW());
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_deduct_stock_for_paid_order ON pos_schema.orders;
CREATE TRIGGER trg_deduct_stock_for_paid_order
BEFORE UPDATE OF status ON pos_schema.orders
FOR EACH ROW EXECUTE FUNCTION pos_schema.fn_deduct_stock_for_paid_order();

-- Mantiene el estado de la mesa a partir de la comanda activa.
CREATE OR REPLACE FUNCTION pos_schema.fn_sync_table_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.table_id IS NOT NULL
       AND (OLD.table_id IS DISTINCT FROM NEW.table_id OR NEW.status IN ('PAGADO','ANULADO')) THEN
        IF NOT EXISTS (
            SELECT 1 FROM pos_schema.orders o
            WHERE o.table_id = OLD.table_id
              AND o.order_id <> NEW.order_id
              AND o.status IN ('BORRADOR','ENVIADO_COCINA','EN_PREPARACION','LISTO','ENTREGADO','PENDIENTE_PAGO')
        ) THEN
            UPDATE pos_schema.dining_tables SET status = 'LIBRE' WHERE table_id = OLD.table_id;
        END IF;
    END IF;

    IF NEW.table_id IS NOT NULL AND NEW.status IN
       ('BORRADOR','ENVIADO_COCINA','EN_PREPARACION','LISTO','ENTREGADO','PENDIENTE_PAGO') THEN
        UPDATE pos_schema.dining_tables SET status = 'OCUPADA' WHERE table_id = NEW.table_id;
    ELSIF NEW.table_id IS NOT NULL AND NEW.status IN ('PAGADO','ANULADO') THEN
        IF NOT EXISTS (
            SELECT 1 FROM pos_schema.orders o
            WHERE o.table_id = NEW.table_id
              AND o.order_id <> NEW.order_id
              AND o.status IN ('BORRADOR','ENVIADO_COCINA','EN_PREPARACION','LISTO','ENTREGADO','PENDIENTE_PAGO')
        ) THEN
            UPDATE pos_schema.dining_tables SET status = 'LIBRE' WHERE table_id = NEW.table_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_table_status ON pos_schema.orders;
CREATE TRIGGER trg_sync_table_status
AFTER INSERT OR UPDATE OF status, table_id ON pos_schema.orders
FOR EACH ROW EXECUTE FUNCTION pos_schema.fn_sync_table_status();

