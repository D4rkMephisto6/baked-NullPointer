-- Actualiza el stock acumulado cada vez que el backend registra un movimiento.
CREATE OR REPLACE FUNCTION pos_schema.fn_apply_inventory_movement()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_new_quantity NUMERIC(14,3);
BEGIN
    IF NEW.quantity_delta < 0 AND NOT EXISTS (
        SELECT 1 FROM pos_schema.inventory_stock s WHERE s.ingredient_id = NEW.ingredient_id
    ) THEN
        RAISE EXCEPTION 'Stock insuficiente para el ingrediente %', NEW.ingredient_id
            USING ERRCODE = '23514';
    END IF;

    INSERT INTO pos_schema.inventory_stock AS s (ingredient_id, quantity_on_hand, updated_at)
    VALUES (NEW.ingredient_id, NEW.quantity_delta, NOW())
    ON CONFLICT (ingredient_id) DO UPDATE
      SET quantity_on_hand = s.quantity_on_hand + EXCLUDED.quantity_on_hand,
          updated_at = NOW()
      WHERE s.quantity_on_hand + EXCLUDED.quantity_on_hand >= 0
    RETURNING quantity_on_hand INTO v_new_quantity;

    IF v_new_quantity IS NULL THEN
        RAISE EXCEPTION 'Stock insuficiente para el ingrediente %. Movimiento: %',
            NEW.ingredient_id, NEW.quantity_delta
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_apply_inventory_movement ON pos_schema.inventory_movements;
CREATE TRIGGER trg_apply_inventory_movement
AFTER INSERT ON pos_schema.inventory_movements
FOR EACH ROW EXECUTE FUNCTION pos_schema.fn_apply_inventory_movement();

-- Al confirmar una compra como RECIBIDA, crea sus entradas de kardex una sola vez.
CREATE OR REPLACE FUNCTION pos_schema.fn_receive_purchase_stock()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
BEGIN
    IF NEW.status = 'RECIBIDA' AND OLD.status IS DISTINCT FROM 'RECIBIDA' THEN
        IF NOT EXISTS (SELECT 1 FROM pos_schema.purchase_items pi WHERE pi.purchase_id = NEW.purchase_id) THEN
            RAISE EXCEPTION 'No se puede recibir la compra % sin detalles', NEW.purchase_id;
        END IF;
        FOR r IN
            SELECT pi.purchase_item_id, pi.ingredient_id, pi.quantity, pi.unit_cost
            FROM pos_schema.purchase_items pi
            WHERE pi.purchase_id = NEW.purchase_id
        LOOP
            INSERT INTO pos_schema.inventory_movements
              (ingredient_id, movement_type, quantity_delta, unit_cost, reference_type, reference_id,
               notes, created_by_user_id)
            VALUES
              (r.ingredient_id, 'COMPRA', r.quantity, r.unit_cost, 'PURCHASE_ITEM', r.purchase_item_id,
               'Ingreso automático por recepción de compra ' || NEW.purchase_id,
               COALESCE(NEW.received_by_user_id, NEW.created_by_user_id));
        END LOOP;
        NEW.received_at := COALESCE(NEW.received_at, NOW());
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_receive_purchase_stock ON pos_schema.purchases;
CREATE TRIGGER trg_receive_purchase_stock
BEFORE UPDATE OF status ON pos_schema.purchases
FOR EACH ROW EXECUTE FUNCTION pos_schema.fn_receive_purchase_stock();

-- Al confirmar una merma, registra salidas de inventario de todos sus detalles.
CREATE OR REPLACE FUNCTION pos_schema.fn_confirm_waste_stock()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
BEGIN
    IF NEW.status = 'CONFIRMADA' AND OLD.status IS DISTINCT FROM 'CONFIRMADA' THEN
        IF NOT EXISTS (SELECT 1 FROM pos_schema.waste_items wi WHERE wi.waste_record_id = NEW.waste_record_id) THEN
            RAISE EXCEPTION 'No se puede confirmar la merma % sin detalles', NEW.waste_record_id;
        END IF;
        FOR r IN
            SELECT wi.waste_item_id, wi.ingredient_id, wi.quantity, wi.estimated_unit_cost
            FROM pos_schema.waste_items wi
            WHERE wi.waste_record_id = NEW.waste_record_id
        LOOP
            INSERT INTO pos_schema.inventory_movements
              (ingredient_id, movement_type, quantity_delta, unit_cost, reference_type, reference_id,
               notes, created_by_user_id)
            VALUES
              (r.ingredient_id, 'MERMA', -r.quantity, r.estimated_unit_cost, 'WASTE_ITEM', r.waste_item_id,
               'Salida automática por merma ' || NEW.waste_record_id,
               COALESCE(NEW.confirmed_by_user_id, NEW.recorded_by_user_id));
        END LOOP;
        NEW.confirmed_at := COALESCE(NEW.confirmed_at, NOW());
    END IF;
    RETURN NEW;
END;
$$;

