       SUM(o.total_amount)::NUMERIC(14,2) AS total_sales
FROM pos_schema.orders o
WHERE o.status = 'PAGADO' AND o.paid_at IS NOT NULL
GROUP BY EXTRACT(HOUR FROM o.paid_at)::INTEGER;

