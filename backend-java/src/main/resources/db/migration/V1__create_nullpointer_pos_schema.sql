       SUM(oi.line_total)::NUMERIC(14,2) AS gross_sales
FROM pos_schema.orders o
JOIN pos_schema.order_items oi ON oi.order_id = o.order_id
WHERE o.status = 'PAGADO' AND oi.status <> 'ANULADO'
