-- ============================================================================
-- NullPointer POS - Migración inicial de PostgreSQL administrada por Flyway.
-- Se ejecuta automáticamente al iniciar Spring Boot dentro de Docker.
-- Esquema de referencia completo para Sprint 1, 2 y 3.
-- Los PIN se almacenan como hash BCrypt desde el backend; nunca en texto plano.
-- ============================================================================


CREATE SCHEMA IF NOT EXISTS auth_schema;
CREATE SCHEMA IF NOT EXISTS pos_schema;

-- ============================================================================
-- AUTH_SCHEMA: identidad, roles, permisos, autenticación y sesiones
-- ============================================================================

CREATE TABLE IF NOT EXISTS auth_schema.roles (
    role_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(40) NOT NULL UNIQUE,
    description   VARCHAR(200),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS auth_schema.permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_key VARCHAR(80) NOT NULL UNIQUE,
    description   VARCHAR(200)
);

-- Relación muchos-a-muchos: un rol puede tener varios permisos y un permiso
-- puede pertenecer a varios roles.
CREATE TABLE IF NOT EXISTS auth_schema.role_permissions (
    role_id       BIGINT NOT NULL REFERENCES auth_schema.roles(role_id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES auth_schema.permissions(permission_id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS auth_schema.users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       BIGINT NOT NULL REFERENCES auth_schema.roles(role_id),
    employee_code VARCHAR(30) NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(160),
    pin_hash      VARCHAR(100) NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_email_nonblank CHECK (email IS NULL OR LENGTH(TRIM(email)) > 0),
    CONSTRAINT users_employee_code_nonblank CHECK (LENGTH(TRIM(employee_code)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower
    ON auth_schema.users (LOWER(email)) WHERE email IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_users_role_active
    ON auth_schema.users (role_id, is_active);

CREATE TABLE IF NOT EXISTS auth_schema.auth_events (
    auth_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT REFERENCES auth_schema.users(user_id) ON DELETE SET NULL,
    employee_code_attempted VARCHAR(30),
    event_type    VARCHAR(30) NOT NULL CHECK (event_type IN ('LOGIN_SUCCESS','LOGIN_FAILED','LOGOUT','TOKEN_REVOKED')),
    ip_address    INET,
    user_agent    TEXT,
    details       JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_auth_events_created_at ON auth_schema.auth_events(created_at DESC);
CREATE INDEX IF NOT EXISTS ix_auth_events_user_created ON auth_schema.auth_events(user_id, created_at DESC);

-- Opcional si el backend implementa refresh tokens. Guardar solamente el hash.
CREATE TABLE IF NOT EXISTS auth_schema.refresh_sessions (
    refresh_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE CASCADE,
    token_hash    VARCHAR(128) NOT NULL UNIQUE,
    expires_at    TIMESTAMPTZ NOT NULL,
    revoked_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT refresh_session_expiry CHECK (expires_at > created_at)
);
CREATE INDEX IF NOT EXISTS ix_refresh_sessions_user ON auth_schema.refresh_sessions(user_id, expires_at);

-- ============================================================================
-- POS_SCHEMA: mesas, menú, comandas, cocina, caja, comprobantes e inventario
-- ============================================================================

-- Sprint 1 / HU-02. Una mesa puede acumular muchas comandas a través del tiempo.
CREATE TABLE IF NOT EXISTS pos_schema.dining_tables (
    table_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_code    VARCHAR(20) NOT NULL UNIQUE,
    area_name     VARCHAR(60) NOT NULL DEFAULT 'SALON',
    capacity      SMALLINT NOT NULL DEFAULT 4 CHECK (capacity > 0),
    status        VARCHAR(20) NOT NULL DEFAULT 'LIBRE'
                  CHECK (status IN ('LIBRE','OCUPADA','FUERA_SERVICIO')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pos_schema.kitchen_stations (
    kitchen_station_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60) NOT NULL UNIQUE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

-- Categoría 1:N productos; category_id padre permite subcategorías opcionales.
CREATE TABLE IF NOT EXISTS pos_schema.product_categories (
    category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id BIGINT REFERENCES pos_schema.product_categories(category_id) ON DELETE SET NULL,
    name          VARCHAR(80) NOT NULL UNIQUE,
    description   VARCHAR(250),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS pos_schema.products (
    product_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   BIGINT NOT NULL REFERENCES pos_schema.product_categories(category_id),
    kitchen_station_id BIGINT REFERENCES pos_schema.kitchen_stations(kitchen_station_id) ON DELETE SET NULL,
    sku           VARCHAR(40) UNIQUE,
    name          VARCHAR(120) NOT NULL,
    description   TEXT,
    image_url     TEXT,
    unit_price    NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    is_available  BOOLEAN NOT NULL DEFAULT TRUE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_products_category_active ON pos_schema.products(category_id, is_active, is_available);
CREATE INDEX IF NOT EXISTS ix_products_station ON pos_schema.products(kitchen_station_id);
CREATE INDEX IF NOT EXISTS ix_products_name_lower ON pos_schema.products(LOWER(name));

-- HU-18. Un cliente puede estar asociado a muchos comprobantes.
CREATE TABLE IF NOT EXISTS pos_schema.customers (
    customer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type VARCHAR(10) NOT NULL CHECK (document_type IN ('DNI','RUC','CE','OTRO')),
    document_number VARCHAR(20) NOT NULL,
    full_name     VARCHAR(180) NOT NULL,
    address       VARCHAR(250),
    phone         VARCHAR(25),
    email         VARCHAR(160),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (document_type, document_number)
);
CREATE INDEX IF NOT EXISTS ix_customers_name_lower ON pos_schema.customers(LOWER(full_name));

-- Sprint 1: cabecera de comanda. Una comanda tiene muchos detalles.
CREATE TABLE IF NOT EXISTS pos_schema.orders (
    order_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code    VARCHAR(30) UNIQUE,
    table_id      BIGINT REFERENCES pos_schema.dining_tables(table_id) ON DELETE RESTRICT,
    waiter_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    paid_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    status        VARCHAR(25) NOT NULL DEFAULT 'BORRADOR'
                  CHECK (status IN ('BORRADOR','ENVIADO_COCINA','EN_PREPARACION','LISTO','ENTREGADO','PENDIENTE_PAGO','PAGADO','ANULADO')),
    notes         TEXT,
    subtotal      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    total_amount  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_at       TIMESTAMPTZ,
    paid_at       TIMESTAMPTZ,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT orders_total_consistency CHECK (total_amount <= subtotal OR subtotal = 0)
);
CREATE INDEX IF NOT EXISTS ix_orders_table_status ON pos_schema.orders(table_id, status);
CREATE INDEX IF NOT EXISTS ix_orders_waiter_created ON pos_schema.orders(waiter_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_orders_status_created ON pos_schema.orders(status, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_orders_paid_at ON pos_schema.orders(paid_at DESC) WHERE status = 'PAGADO';

-- Regla de negocio: no permitir dos comandas activas en la misma mesa.
CREATE UNIQUE INDEX IF NOT EXISTS ux_orders_one_active_per_table
    ON pos_schema.orders(table_id)
    WHERE table_id IS NOT NULL AND status IN ('BORRADOR','ENVIADO_COCINA','EN_PREPARACION','LISTO','ENTREGADO','PENDIENTE_PAGO');

-- HU-03/HU-04/HU-05: detalle con precio histórico y observación por plato.
CREATE TABLE IF NOT EXISTS pos_schema.order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES pos_schema.orders(order_id) ON DELETE CASCADE,
    product_id    BIGINT REFERENCES pos_schema.products(product_id) ON DELETE SET NULL,
    product_name_snapshot VARCHAR(120) NOT NULL,
    quantity      INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price    NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    notes         VARCHAR(500),
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                  CHECK (status IN ('PENDIENTE','EN_PREPARACION','LISTO','ENTREGADO','ANULADO')),
    line_total    NUMERIC(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_order_items_order ON pos_schema.order_items(order_id);
CREATE INDEX IF NOT EXISTS ix_order_items_product ON pos_schema.order_items(product_id);
CREATE INDEX IF NOT EXISTS ix_order_items_status ON pos_schema.order_items(status);

CREATE TABLE IF NOT EXISTS pos_schema.order_status_history (
    order_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES pos_schema.orders(order_id) ON DELETE CASCADE,
    previous_status VARCHAR(25),
    new_status    VARCHAR(25) NOT NULL,
    changed_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE SET NULL,
    change_reason TEXT,
    changed_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_order_status_history_order ON pos_schema.order_status_history(order_id, changed_at DESC);

CREATE TABLE IF NOT EXISTS pos_schema.order_item_status_history (
    order_item_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES pos_schema.order_items(order_item_id) ON DELETE CASCADE,
    previous_status VARCHAR(20),
    new_status    VARCHAR(20) NOT NULL,
    changed_by_user_id BIGINT REFERENCES auth_schema.users(user_id) ON DELETE SET NULL,
    changed_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_item_status_history_item ON pos_schema.order_item_status_history(order_item_id, changed_at DESC);

-- HU-06: historial de transferencias de mesa.
CREATE TABLE IF NOT EXISTS pos_schema.table_transfers (
    table_transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES pos_schema.orders(order_id) ON DELETE RESTRICT,
    from_table_id BIGINT NOT NULL REFERENCES pos_schema.dining_tables(table_id) ON DELETE RESTRICT,
    to_table_id   BIGINT NOT NULL REFERENCES pos_schema.dining_tables(table_id) ON DELETE RESTRICT,
    transferred_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    reason        VARCHAR(250),
    transferred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT table_transfer_different_tables CHECK (from_table_id <> to_table_id)
);
CREATE INDEX IF NOT EXISTS ix_table_transfers_order ON pos_schema.table_transfers(order_id, transferred_at DESC);

-- HU-17: descuento/promoción aplicado a una comanda con autorización trazable.
CREATE TABLE IF NOT EXISTS pos_schema.order_adjustments (
    order_adjustment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES pos_schema.orders(order_id) ON DELETE CASCADE,
    adjustment_type VARCHAR(20) NOT NULL CHECK (adjustment_type IN ('DESCUENTO','PROMOCION')),
    calculation_type VARCHAR(15) NOT NULL CHECK (calculation_type IN ('MONTO','PORCENTAJE')),
    input_value   NUMERIC(12,2) NOT NULL CHECK (input_value > 0),
    amount_applied NUMERIC(12,2) NOT NULL CHECK (amount_applied > 0),
    reason        VARCHAR(250) NOT NULL,
    applied_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    authorized_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_adjustments_order ON pos_schema.order_adjustments(order_id);

-- HU-29: motivo de anulación y quién la solicitó/autorizó.
CREATE TABLE IF NOT EXISTS pos_schema.order_cancellations (
    order_cancellation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL UNIQUE REFERENCES pos_schema.orders(order_id) ON DELETE RESTRICT,
    reason        VARCHAR(500) NOT NULL,
    cancelled_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    authorized_by_user_id BIGINT NOT NULL REFERENCES auth_schema.users(user_id) ON DELETE RESTRICT,
    cancelled_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Outbox para publicar eventos confiables a la pantalla KDS vía WebSocket.
-- Spring debe insertar el evento en la misma transacción que crea/actualiza la comanda.
CREATE TABLE IF NOT EXISTS pos_schema.outbox_events (
    outbox_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(60) NOT NULL,
    aggregate_id   BIGINT NOT NULL,
    event_type     VARCHAR(80) NOT NULL,
    payload        JSONB NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    published_at   TIMESTAMPTZ,
    attempts       INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error     TEXT
);
CREATE INDEX IF NOT EXISTS ix_outbox_pending ON pos_schema.outbox_events(created_at)
    WHERE published_at IS NULL;

